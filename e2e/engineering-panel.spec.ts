import { test, expect, chromium } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { TestApiClient } from "./fixtures";

test("the issue panel freezes scope, records a human answer, and resumes the same phase on a queued run", async ({ baseURL }, testInfo) => {
  test.setTimeout(120000);
  test.skip(process.env.MULTICA_ENGINEERING_ENABLED !== "true" || !process.env.MULTICA_ENGINEERING_BROWSER || !process.env.MULTICA_ENGINEERING_CLI, "Requires the managed local service, CLI, and explicit browser binary");
  const api = new TestApiClient(); await api.loginLocally();
  const workspace = (await api.getWorkspaces()).find(value => value.slug === "loopwork-local")!;
  api.setWorkspaceId(workspace.id); api.setWorkspaceSlug(workspace.slug);
  const directory = await mkdtemp(join(tmpdir(), "engineering-panel-"));
  const repository = join(directory, "repository"); execFileSync("git", ["init", "-q", repository]);
  const git = (...args: string[]) => execFileSync("git", ["-C", repository, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
  git("config", "user.name", "Panel fixture"); git("config", "user.email", "fixture@example.invalid");
  await writeFile(join(repository, "index.html"), "<!doctype html><h1>Ready</h1>"); git("add", "."); git("commit", "-qm", "Initialize fixture");
  const browser = await chromium.launch({ executablePath: process.env.MULTICA_ENGINEERING_BROWSER });
  const context = await browser.newContext({ viewport: { width: 1280, height: 960 } });
  await context.addInitScript(() => { localStorage.setItem("multica:chat:isOpen", "false"); });
  const page = await context.newPage();
  try {
    const fixture = await api.seedEngineeringRun(); await api.finishEngineeringRun(fixture.taskId);
    const project = await api.createProject(`Engineering panel ${fixture.issueId}`);
    await api.attachEngineeringProject(fixture.taskId, project.id, repository);
    await page.goto(`${baseURL}/`, { waitUntil: "domcontentloaded" });
    await expect(page).toHaveURL(new RegExp(`/${workspace.slug}/issues$`), { timeout: 30000 });
    await page.goto(`${baseURL}/${workspace.slug}/issues/${fixture.issueId}`, { waitUntil: "domcontentloaded" });
    const panel = page.getByRole("region", { name: "Engineering delivery" });
    await panel.getByRole("button", { name: "Configure delivery" }).click({ timeout: 30000 });
    const dialog = page.getByRole("dialog");
    await dialog.getByLabel("Repository path").fill(repository);
    await expect(dialog.getByRole("spinbutton", { name: "Automatic rework limit" })).toHaveValue("3");
    const policyScreenshot = testInfo.outputPath("configure-rework-policy.png"); await dialog.screenshot({ path: policyScreenshot });
    await testInfo.attach("Explicit bounded rework policy", { path: policyScreenshot, contentType: "image/png" });
    await dialog.getByRole("switch", { name: "Include development" }).click();
    await dialog.getByRole("switch", { name: "Continue automatically" }).click();
    await dialog.getByRole("combobox", { name: "Independent verification agent" }).click();
    await page.getByRole("option", { name: `Engineering fixture ${fixture.agentId}`, exact: true }).click();
    await dialog.getByLabel("Scope", { exact: true }).fill("The fixture displays Ready");
    await dialog.getByLabel("Expected result", { exact: true }).fill("A browser sees the exact Ready heading");
    const configurationScreenshot = testInfo.outputPath("configure-delivery.png"); await dialog.screenshot({ path: configurationScreenshot });
    await testInfo.attach("Engineering configuration", { path: configurationScreenshot, contentType: "image/png" });
    const frozen = page.waitForResponse(response => response.request().method() === "POST" && /\/engineering\/verification\/?$/.test(new URL(response.url()).pathname));
    await dialog.getByRole("button", { name: "Freeze scope" }).click(); expect((await frozen).status()).toBe(200);
    await expect(dialog).not.toBeVisible();
    const firstQueued = page.waitForResponse(response => response.request().method() === "POST" && new URL(response.url()).pathname.endsWith("/engineering/run"));
    await panel.getByRole("button", { name: "Start run" }).click();
    const firstResponse = await firstQueued; expect(firstResponse.status()).toBe(202);
    let run = await api.claimEngineeringRun((await firstResponse.json()).id); await api.bindEngineeringRepository(run.taskId, repository);
    const cli = (name: string, payload?: unknown) => JSON.parse(execFileSync(resolve(process.env.MULTICA_ENGINEERING_CLI!), ["engineering", name, ...(payload ? ["--payload", JSON.stringify(payload)] : [])], {
      cwd: directory, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], timeout: 20000,
      env: { ...process.env, MULTICA_SERVER_URL: run.apiBase, MULTICA_WORKSPACE_ID: workspace.id, MULTICA_TASK_ID: run.taskId, MULTICA_AGENT_ID: run.agentId, MULTICA_TOKEN: run.taskToken },
    }));
    let state = cli("start"); const draftId = state.draft.id;
    const command = (value: unknown) => { state = cli("command", { expected_sequence: state.draft.sequence, command: value }); };
    command({ type: "phase.complete" });
    command({ type: "runtime-input.put", key: "entry", title: "Fixture entry", question: "Which fixture should be checked?", why: "Need isolated data", recommendation: "Use the local fixture" });
    command({ type: "phase.complete" }); expect(state.draft.status).toBe("waiting_for_answers");
    await api.finishEngineeringRun(run.taskId);
    await panel.getByRole("button", { name: "Refresh engineering delivery" }).click();
    await expect(panel.getByText("Which fixture should be checked?")).toBeVisible();
    await panel.scrollIntoViewIfNeeded();
    const questionScreenshot = testInfo.outputPath("human-checkpoint.png"); await panel.screenshot({ path: questionScreenshot });
    await testInfo.attach("Human engineering checkpoint", { path: questionScreenshot, contentType: "image/png" });
    await page.setViewportSize({ width: 390, height: 844 }); await panel.scrollIntoViewIfNeeded();
    const narrowBox = await panel.boundingBox(); expect(narrowBox!.x).toBeGreaterThanOrEqual(0); expect(narrowBox!.width).toBeLessThanOrEqual(390);
    const narrowScreenshot = testInfo.outputPath("human-checkpoint-narrow.png"); await panel.screenshot({ path: narrowScreenshot });
    await testInfo.attach("Narrow human checkpoint", { path: narrowScreenshot, contentType: "image/png" });
    await page.setViewportSize({ width: 1280, height: 960 });
    await panel.getByRole("button", { name: "Use recommendation" }).click();
    expect((await api.engineeringVerification(fixture.issueId, "inspect")).draft.runtimeInputs[0].answer).toBeNull();
    await panel.getByLabel("Your answer").fill("Use the isolated local fixture");
    await panel.getByRole("button", { name: "Submit answer" }).click();
    const continuation = panel.getByRole("button", { name: "Continue run" }); await expect(continuation).toBeVisible();
    const answered = await api.engineeringVerification(fixture.issueId, "inspect");
    expect(answered.draft.runtimeInputs[0].answer).toMatchObject({ text: "Use the isolated local fixture", userId: fixture.userId });
    const nextQueued = page.waitForResponse(response => response.request().method() === "POST" && new URL(response.url()).pathname.endsWith("/engineering/run"));
    await continuation.click(); const nextResponse = await nextQueued; expect(nextResponse.status()).toBe(202);
    const next = await nextResponse.json(); expect(next.agent_id).toBe(fixture.agentId);
    run = await api.claimEngineeringRun(next.id); await api.bindEngineeringRepository(run.taskId, repository);
    state = cli("start"); expect(state.draft.id).toBe(draftId); expect(state.draft.phase).toBe("plan");
    expect(state.draft.runtimeInputs[0].answer.text).toBe("Use the isolated local fixture");
    command({ type: "artifact.put", ref: "verification.scenarios", key: "s1", content: "channel: frontend\ntitle: Heading\nsetup: Open committed fixture\nsteps: Observe h1\nexpected: Ready\ncoverageRefs: [scope-1]" });
    command({ type: "phase.complete" });
    const observation = await context.newPage(); await observation.goto(pathToFileURL(join(repository, "index.html")).href);
    await expect(observation.getByRole("heading", { name: "Ready", exact: true })).toBeVisible(); await observation.close();
    command({ type: "artifact.put", ref: "verification.results", key: "s1", content: "status: passed\nevidence: Independent browser observed exact Ready heading" });
    command({ type: "phase.complete" }); command({ type: "artifact.put", ref: "verification.evidence-review", content: "summary: Browser observation matches the frozen oracle" });
    command({ type: "phase.complete" }); command({ type: "phase.complete" }); await api.finishEngineeringRun(run.taskId);
    await panel.getByRole("button", { name: "Refresh engineering delivery" }).click(); await expect(panel.getByText("Verification passed", { exact: true })).toBeVisible();
    const resultScreenshot = testInfo.outputPath("verified-delivery.png"); await panel.screenshot({ path: resultScreenshot });
    await testInfo.attach("Verified engineering delivery", { path: resultScreenshot, contentType: "image/png" });
  } finally { await context.close(); await browser.close(); await api.cleanup(); await rm(directory, { recursive: true, force: true }); }
});
